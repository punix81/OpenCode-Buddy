"""Local mock display preview. Serve firmware pixels or export native-size review sheets."""
import argparse
import io
import subprocess
from http.server import BaseHTTPRequestHandler, HTTPServer
from pathlib import Path
from urllib.parse import urlparse, parse_qs

from PIL import Image, ImageDraw

HERE = Path(__file__).resolve().parent
STATES = ['Offline', 'Idle', 'Thinking', 'Generating', 'Working', 'Permission',
          'Input needed', 'Success', 'Error', 'Compacting', 'Retrying', 'Interrupted']
SCREENS = ['Buddy', 'Session', 'Tokens', 'Tools', 'MCP Radar', 'System']
LANGUAGES = ['en', 'fr', 'de']
PROFILES = ['Typical', 'Missing', 'Extreme', 'Degraded link', 'MCP 12/8', 'Interaction',
            'LIVE fixture']


def frame(screen, state, profile=0, quiet=0, time=960, age=960, previous=1, page_age=960,
          language=0):
    args = [screen, state, profile, quiet, time, age, previous, page_age, language]
    pixels = subprocess.check_output([HERE / '.build/preview', *map(str, args)])
    return Image.open(io.BytesIO(pixels)).convert('RGB')


def sheet(cells, columns, name, destination):
    """Write a native-size review sheet; each cell keeps the 240 x 240 pixels."""
    rows = (len(cells) + columns - 1) // columns
    canvas = Image.new('RGB', (columns * 250, rows * 258), '#10151e')
    pen = ImageDraw.Draw(canvas)
    mask = Image.new('L', (240, 240))
    ImageDraw.Draw(mask).ellipse((0, 0, 239, 239), fill=255)
    for index, (image, label) in enumerate(cells):
        x, y = index % columns * 250, index // columns * 258
        canvas.paste(image, (x + 5, y + 5), mask)
        pen.text((x + 125, y + 250), label, fill='#cad3df', anchor='mm')
    canvas.save(destination / name)


def sheets():
    destination = HERE.parents[1] / 'docs/design/previews'
    destination.mkdir(parents=True, exist_ok=True)

    sheet([(frame(0, state), STATES[state]) for state in range(12)], 4,
          'expressions.png', destination)

    for language, code in enumerate(LANGUAGES):
        cells = [(frame(screen, 2, language=language), SCREENS[screen]) for screen in range(6)]
        name = 'screens.png' if language == 0 else f'screens-{code}.png'
        sheet(cells, 3, name, destination)

    sheet([(frame(screen, 0, 1), SCREENS[screen]) for screen in range(6)], 3,
          'missing.png', destination)
    sheet([(frame(screen, 2, 2), SCREENS[screen]) for screen in range(6)], 3,
          'extremes.png', destination)
    sheet([(frame(screen, 0, 3), SCREENS[screen]) for screen in range(6)], 3,
          'offline.png', destination)
    sheet([(frame(screen, 2, 6), f'LIVE fixture · {SCREENS[screen]}') for screen in (0, 1, 5)], 3,
          'live.png', destination)
    sheet([(frame(screen, 5, 5), SCREENS[screen]) for screen in (0, 1, 3)], 3,
          'interaction.png', destination)
    sheet([(frame(4, 2, 4, language=language), f'MCP 12/8 · {code}') for language, code in
           enumerate(LANGUAGES)], 3, 'mcp-12.png', destination)
    sheet([(frame(0, 2, 0, 0), 'Loud'), (frame(0, 2, 0, 1), 'Quiet')], 2,
          'quiet.png', destination)

    # Before/after: the Phase 3.1 sheets are kept under phase-3/.
    legacy = destination / 'phase-3'
    if (legacy / 'screens.png').exists():
        old = Image.open(legacy / 'screens.png').convert('RGB')
        new = Image.open(destination / 'screens.png').convert('RGB')
        comparison = Image.new('RGB', (max(old.width, new.width), old.height + new.height + 40),
                               '#10151e')
        comparison.paste(old, (0, 30))
        comparison.paste(new, (0, old.height + 40))
        pen = ImageDraw.Draw(comparison)
        pen.text((10, 8), 'Phase 3.1 (before)', fill='#cad3df')
        pen.text((10, old.height + 18), 'Phase 4 (after)', fill='#cad3df')
        comparison.save(destination / 'comparison-phase4.png')

    # The index contains the usage guide; keep it with the sheets.
    (destination / 'README.md').write_text(
        '# Display previews\n\n'
        'Native 240 x 240 renders from `tools/ui-preview` (mock fixture, not hardware). '
        'The six dashboards, the twelve expressions, the missing/extreme/offline profiles, '
        'the 12-server MCP subset and the English/French/German sheets are regenerated by '
        '`python3 preview.py --sheets`.\n\n'
        'The Phase 3.1 sheets under `phase-3/` are the before images; '
        '`comparison-phase4.png` stacks them above the Phase 4 sheets.\n\n'
        'The LIVE fixture (`live.png`) previews the LIVE footer wording with simulated data; '
        'it is a layout fixture, not a recording of a live session.\n',
        encoding='utf-8')


class Handler(BaseHTTPRequestHandler):
    def do_GET(self):
        url = urlparse(self.path)
        if url.path == '/':
            body = (HERE / 'index.html').read_bytes()
            kind = 'text/html; charset=utf-8'
        elif url.path == '/frame':
            try:
                values = list(map(int, parse_qs(url.query)['v'][0].split(',')))
                limits = (5, 11, 6, 1, 2**30, 2**30, 11, 2**30, 2)
                if len(values) != 9 or any(v < 0 or v > n for v, n in zip(values, limits)):
                    raise ValueError()
                output = io.BytesIO()
                frame(*values).save(output, 'PNG', compress_level=1)
                body, kind = output.getvalue(), 'image/png'
            except (KeyError, ValueError):
                self.send_error(400)
                return
        else:
            self.send_error(404)
            return
        self.send_response(200)
        self.send_header('Content-Type', kind)
        self.send_header('Cache-Control', 'no-store')
        self.end_headers()
        try:
            self.wfile.write(body)
        except (BrokenPipeError, ConnectionResetError):
            pass  # Tab closed before its frame arrived.

    def log_message(self, fmt, *args):
        if args[1] != '200':
            super().log_message(fmt, *args)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--sheets', action='store_true')
    parser.add_argument('--port', type=int, default=8765)
    args = parser.parse_args()
    subprocess.run(['make', '-s', '-j4'], cwd=HERE, check=True)
    if args.sheets:
        sheets()
    else:
        with HTTPServer(('127.0.0.1', args.port), Handler) as server:
            print(f'MOCK display preview · http://127.0.0.1:{server.server_port}/', flush=True)
            server.serve_forever()

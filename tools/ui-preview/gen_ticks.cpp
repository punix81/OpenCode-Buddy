// Generates firmware/src/TickTables.h: the exact pixel spans produced by the
// pinned LovyanGFX fillArc for the Session and Tokens tick rings. Rendering the
// spans with drawFastHLine is pixel-identical to calling fillArc per tick, but
// avoids the full-radius scan on every frame. Run from tools/ui-preview:
//   make ticks
#include <cstdint>
#include <cstdio>
#include <cstdlib>

#include "Theme.h"

using namespace buddy::ui;
using buddy::kCanvasSize;

namespace {

struct Span {
  uint8_t y, x0, x1;
};

Span spans[4096];
int spanCount = 0;

void collect(Canvas& g) {
  const auto* buffer = static_cast<const uint8_t*>(g.getBuffer());
  if (buffer == nullptr) return;
  for (int y = 0; y < kCanvasSize; ++y) {
    int x = 0;
    while (x < kCanvasSize) {
      if (buffer[y * kCanvasSize + x] == 0) {
        ++x;
        continue;
      }
      const int start = x;
      while (x < kCanvasSize && buffer[y * kCanvasSize + x] != 0) ++x;
      if (spanCount < static_cast<int>(sizeof(spans) / sizeof(spans[0]))) {
        spans[spanCount++] = {static_cast<uint8_t>(y), static_cast<uint8_t>(start),
                              static_cast<uint8_t>(x - 1)};
      }
    }
  }
}

void tick(Canvas& g, int radius, int width, int start, int length) {
  g.fillScreen(0);
  spanCount = 0;
  g.fillArc(center, center, radius, radius - width + 1, start % 360, (start + length) % 360, 1);
  collect(g);
}

void emit(const char* name, int count, int radius, int widthAt(int), int startAt(int), int length) {
  Canvas g;
  if (!initCanvas(g)) {
    std::fprintf(stderr, "canvas init failed\n");
    std::exit(1);
  }
  Span all[4096];
  int total = 0;
  int groups[64];
  int counts[64];
  for (int i = 0; i < count; ++i) {
    tick(g, radius, widthAt(i), startAt(i), length);
    groups[i] = total;
    counts[i] = spanCount;
    for (int s = 0; s < spanCount; ++s) all[total + s] = spans[s];
    total += spanCount;
  }
  std::printf("inline constexpr TickSpan k%sSpans[] = {\n", name);
  for (int i = 0; i < total; ++i) {
    std::printf("    {%u, %u, %u},\n", all[i].y, all[i].x0, all[i].x1);
  }
  std::printf("};\ninline constexpr TickGroup k%sGroups[] = {\n", name);
  for (int i = 0; i < count; ++i) {
    std::printf("    {%d, %d},\n", groups[i], counts[i]);
  }
  std::printf("};\n");
  std::fprintf(stderr, "%s: %d ticks, %d spans\n", name, count, total);
}

}  // namespace

int main() {
  std::printf("// Generated by tools/ui-preview/gen_ticks.cpp from the pinned LovyanGFX fillArc.\n");
  std::printf("// Do not edit by hand; run `make ticks` if the tick geometry changes.\n");
  std::printf("#pragma once\n#include <cstdint>\n\nnamespace buddy::ui {\n");
  std::printf("struct TickSpan { uint8_t y, x0, x1; };\n");
  std::printf("struct TickGroup { uint16_t first; uint8_t count; };\n\n");
  emit("Session", 36, 100, [](int i) { return i % 3 ? 2 : 5; }, [](int i) { return 5 + i * 10; }, 2);
  emit("Tokens", 28, 98, [](int) { return 4; }, [](int i) { return 145 + i * 9; }, 7);
  std::printf("\n}  // namespace buddy::ui\n");
  return 0;
}
